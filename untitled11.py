# REQUIREMENT 2 — Specialization via Inheritance
# ─────────────────────────────────────────────────────────────

class LabCourse(Course):
    """
    Type A — Practical Lab.
    Adds a flat lab equipment fee on top of base tuition.
    """

    EQUIPMENT_FEE = 150.00  # flat fee per semester

    def __init__(self, course_id, name, credit_hours, cost_per_credit, safety_gear_required: bool = False):
        super().__init__(course_id, name, credit_hours, cost_per_credit)
        self.__safety_gear_required = safety_gear_required  # unique property

    @property
    def safety_gear_required(self):
        return self.__safety_gear_required

    # REQUIREMENT 4 — Polymorphism: LabCourse's own version of calculate_tuition
    def calculate_tuition(self) -> float:
        return self.base_tuition() + self.EQUIPMENT_FEE

    def display_course_info(self) -> str:
        gear = "Yes ⚠️" if self.__safety_gear_required else "No"
        return (
            f"  [{self.course_id}] {self.name}\n"
            f"       Type          : Practical Lab 🔬\n"
            f"       Credit Hours  : {self.credit_hours} hrs\n"
            f"       Equipment Fee : ${self.EQUIPMENT_FEE:.2f} (flat)\n"
            f"       Safety Gear   : {gear}\n"
            f"       Est. Tuition  : ${self.calculate_tuition():.2f}"
        )


class LectureCourse(Course):
    """
    Type B — Theoretical Lecture.
    Adds a 5% technology fee on top of base tuition.
    """

    TECH_FEE_RATE = 0.05  # 5% surcharge

    def __init__(self, course_id, name, credit_hours, cost_per_credit,
                 hall_capacity: int = 200, online_link: str = ""):
        super().__init__(course_id, name, credit_hours, cost_per_credit)
        self.__hall_capacity = hall_capacity   # unique property
        self.__online_link = online_link

    @property
    def hall_capacity(self):
        return self.__hall_capacity

    @hall_capacity.setter
    def hall_capacity(self, value: int):
        if value < 1:
            raise ValueError("Hall capacity must be at least 1.")
        self.__hall_capacity = value

    # REQUIREMENT 4 — Polymorphism: LectureCourse's own version of calculate_tuition
    def calculate_tuition(self) -> float:
        base = self.base_tuition()
        return base + base * self.TECH_FEE_RATE

    def display_course_info(self) -> str:
        link_info = self.__online_link if self.__online_link else "In-person only"
        return (
            f"  [{self.course_id}] {self.name}\n"
            f"       Type          : Theoretical Lecture 📖\n"
            f"       Credit Hours  : {self.credit_hours} hrs\n"
            f"       Tech Fee      : {int(self.TECH_FEE_RATE * 100)}% surcharge\n"
            f"       Hall Capacity : {self.__hall_capacity} seats\n"
            f"       Online Link   : {link_info}\n"
            f"       Est. Tuition  : ${self.calculate_tuition():.2f}"
        )



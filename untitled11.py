def print_banner():
    print("\n" + "=" * 58)
    print("   🎓  INTERACTIVE UNIVERSITY REGISTRATION SYSTEM")
    print("=" * 58)

def print_menu():
    print("\n┌─────────────────────────────────┐")
    print("│          STUDENT PORTAL          │")
    print("├─────────────────────────────────┤")
    print("│  [1]  View Available Courses     │")
    print("│  [2]  Register for a Course      │")
    print("│  [3]  View My Schedule           │")
    print("│  [4]  Drop a Course              │")
    print("│  [5]  Print Tuition Bill         │")
    print("│  [0]  Exit                       │")
    print("└─────────────────────────────────┘")

def view_catalogue(catalogue: dict):
    print("\n" + "─" * 58)
    print("  📋  AVAILABLE COURSES THIS SEMESTER")
    print("─" * 58)
    print("\n  ── Theoretical Lectures ──")
    for course in catalogue.values():
        if isinstance(course, LectureCourse):
            print(f"\n{course.display_course_info()}")
    print("\n  ── Practical Labs ──")
    for course in catalogue.values():
        if isinstance(course, LabCourse):
            print(f"\n{course.display_course_info()}")
    print("─" * 58)

def register_course(catalogue: dict, schedule: StudentSchedule):
    course_id = input("\n  Enter Course ID to register (e.g. CS101): ").strip().upper()
    if course_id not in catalogue:
        print(f"  ❌  Course '{course_id}' not found. Check the catalogue.")
        return
    if schedule.add_course(catalogue[course_id]):
        print(f"  ✅  '{catalogue[course_id].name}' added to your schedule.")
    else:
        print(f"  ⚠️  You are already registered for '{catalogue[course_id].name}'.")

def drop_course(schedule: StudentSchedule):
    if schedule.is_empty():
        print("  ⚠️  Your schedule is empty — nothing to drop.")
        return
    course_id = input("\n  Enter Course ID to drop: ").strip().upper()
    if schedule.remove_course(course_id):
        print(f"  ✅  Course '{course_id}' removed from your schedule.")
    else:
        print(f"  ❌  Course '{course_id}' is not in your schedule.")

def main():
    print_banner()
    student_name = input("\n  Welcome! Please enter your name: ").strip() or "Student"
    schedule = StudentSchedule(student_name)
    catalogue = build_catalogue()
    print(f"\n  Hello, {student_name}! Use the menu below to manage your registration.")

    while True:
        print_menu()
        choice = input("\n  Select an option: ").strip()

        if choice == "1":
            view_catalogue(catalogue)
        elif choice == "2":
            register_course(catalogue, schedule)
        elif choice == "3":
            schedule.print_schedule()
        elif choice == "4":
            drop_course(schedule)
        elif choice == "5":
            schedule.print_tuition_bill()
        elif choice == "0":
            print(f"\n  👋  Goodbye, {student_name}! See you next semester.\n")
            break
        else:
            print("  ❌  Invalid choice. Please enter a number from 0 to 5.")

if __name__ == "__main__":
    main()
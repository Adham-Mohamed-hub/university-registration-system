class StudentSchedule:
    def __init__(self, student_name: str):
        self.__student_name = student_name
        self.__courses: list[Course] = []

    @property
    def student_name(self):
        return self.__student_name

    def add_course(self, course: Course) -> bool:
        for c in self.__courses:
            if c.course_id == course.course_id:
                return False
        self.__courses.append(course)
        return True

    def remove_course(self, course_id: str) -> bool:
        for c in self.__courses:
            if c.course_id == course_id:
                self.__courses.remove(c)
                return True
        return False

    def is_empty(self) -> bool:
        return len(self.__courses) == 0

    def print_schedule(self):
        if self.is_empty():
            print("  ⚠️  Your schedule is empty.")
            return
        print(f"\n  Registered courses for {self.__student_name}:")
        for i, course in enumerate(self.__courses, 1):
            print(f"\n  {i}. {course.display_course_info()}")

    def print_tuition_bill(self):
        if self.is_empty():
            print("  ⚠️  No courses registered. Nothing to bill.")
            return

        W = 58
        print("\n" + "=" * W)
        print("       🎓  UNIVERSITY TUITION BILL")
        print("=" * W)
        print(f"  Student : {self.__student_name}")
        print("-" * W)
        print(f"  {'Course':<30} {'Type':<10} {'Tuition':>10}")
        print("-" * W)

        total = 0.0
        for course in self.__courses:
            tuition = course.calculate_tuition()   # ← polymorphic call
            total += tuition
            kind = "Lab" if isinstance(course, LabCourse) else "Lecture"
            print(f"  {course.name:<30} {kind:<10} ${tuition:>9.2f}")

        print("-" * W)
        print(f"  {'TOTAL SEMESTER FEES':<40} ${total:>9.2f}")
        print("=" * W)
        print("  Thank you for registering. Good luck this semester! 🌟")
        print("=" * W + "\n")



        LectureCourse("MATH201", "Linear Algebra",                   3, 45.0, hall_capacity=120),
        LectureCourse("PHYS101", "Physics I",                        3, 48.0, hall_capacity=200,
                      online_link="https://meet.university.edu/phys101"),
        LectureCourse("AI301",   "Artificial Intelligence",          3, 60.0, hall_capacity=100,
                      online_link="https://meet.university.edu/ai301"),
        LectureCourse("ARCH201", "Computer Architecture",            3, 55.0, hall_capacity=80),
        LectureCourse("SIG301",  "Signals & Systems",                3, 52.0, hall_capacity=90),
        LabCourse("CS101L",   "Computer Science Lab",  1, 40.0, safety_gear_required=False),
        LabCourse("PHYS101L", "Physics Lab",           1, 40.0, safety_gear_required=True),
